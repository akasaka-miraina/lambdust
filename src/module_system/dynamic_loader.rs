//! Dynamic library loading and hot-reload support.
//!
//! This module provides comprehensive dynamic loading capabilities including:
//! - Runtime library loading and unloading
//! - Hot-reload support with dependency tracking
//! - File system monitoring for automatic reloading
//! - Safe hot-swapping of library implementations

use super::{Module, ModuleError, ModuleId, runtime_integration};
