    /// Enables hot-reload event monitoring.
    pub fn enable_event_monitoring(&mut self) -> mpsc::Receiver<ReloadEvent> {
        let (sender, receiver) = mpsc::channel();
        self.reload_sender = Some(sender);
        receiver
    }

    /// Gets information about all active libraries.
    pub fn get_active_libraries(&self) -> HashMap<ModuleId, DynamicLibraryInstance> {
        let active_libs = self.active_libraries.try_read().unwrap();
        active_libs.clone()
    }

    /// Checks for file modifications and triggers reloads.
    pub fn check_for_modifications(
        &mut self,
        instantiator: &mut runtime_integration::LibraryInstantiator,
    ) -> Result<Vec<ModuleId>> {
        let mut reloaded_modules = Vec::new();
        let modifications = self.detect_file_modifications()?;

        for (module_id, _modified_path) in modifications {
            if let Ok(()) = self.reload_library(&module_id, instantiator) {
                reloaded_modules.push(module_id);
            }
        }

        Ok(reloaded_modules)
    }

    /// Detects file modifications for all monitored libraries.
    fn detect_file_modifications(&self) -> Result<Vec<(ModuleId, PathBuf)>> {
        let mut modifications = Vec::new();
        let active_libs = self.active_libraries.try_read().unwrap();

        for (module_id, instance) in active_libs.iter() {
            if let Some(source_path) = &instance.source_path {
                if let Ok(metadata) = fs::metadata(source_path) {
                    if let Ok(modified_time) = metadata.modified() {
                        if modified_time > instance.last_modified {
                            modifications.push((module_id.clone(), source_path.clone()));
                        }
                    }
                }
            }
        }

        Ok(modifications)
    }

    /// Loads a module from a file path.
    fn load_module_from_file(&self, path: &Path, module_id: &ModuleId) -> Result<Module> {
        let source_code = fs::read_to_string(path).map_err(|e| {
            Error::io_error(format!(
                "Failed to read library file {}: {}",
                path.display(),
                e
            ))
        })?;

        // Parse the source code
        let binding = path.to_string_lossy();
        let mut lexer = Lexer::new(&source_code, Some(&binding));
        let tokens = lexer.tokenize()?;
        let mut parser = Parser::new(tokens);
        let program = parser.try_parse_program()?;

        // Look for define-library forms
        for expr in &program.expressions {
            if let Expr::DefineLibrary {
                name,
                imports,
                exports,
                body,
            } = &expr.inner
            {
                // Create module from define-library form
                let parsed_module = Module {
                    id: module_id.clone(),
                    exports: HashMap::new(), // Would be populated from exports
                    dependencies: Vec::new(), // Would be populated from imports
                    source: Some(super::ModuleSource::File(path.to_path_buf())),
                    metadata: super::ModuleMetadata {
                        description: Some(format!("Library: {}", name.join(" "))),
                        ..Default::default()
                    },
                };
                return Ok(parsed_module);
            }
        }

        // Fallback: create a basic module
        Ok(Module {
            id: module_id.clone(),
            exports: HashMap::new(),
            dependencies: Vec::new(),
            source: Some(super::ModuleSource::File(path.to_path_buf())),
            metadata: super::ModuleMetadata::default(),
        })
    }

    /// Gets the source path for a module.
    fn get_source_path_for_module(&self, module: &Module) -> Option<PathBuf> {
        match &module.source {
            Some(super::ModuleSource::File(path)) => Some(path.clone()),
            _ => None,
        }
    }

    /// Tracks dependencies for a module.
    fn track_dependencies(&mut self, module: &Module) {
        let module_id = &module.id;

        // Track forward dependencies
        self.dependency_tracker.forward_deps.insert(
            module_id.clone(),
            module.dependencies.iter().cloned().collect(),
        );

        // Track reverse dependencies
        for dep_id in &module.dependencies {
            self.dependency_tracker
                .reverse_deps
                .entry(dep_id.clone())
                .or_default()
                .insert(module_id.clone());
        }
    }

